-- 9. SIMILARITY SEARCH PERFORMANCE TESTING
-- =============================================

-- Function to test vector search performance
CREATE OR REPLACE FUNCTION test_vector_search_performance(
    test_embedding vector(512),
    limit_results int DEFAULT 100
)
RETURNS TABLE (
    search_type text,
    execution_time_ms float,
    results_returned bigint
) AS $$
DECLARE
    start_time timestamp;
    end_time timestamp;
    result_count bigint;
BEGIN
    -- Test 1: Cosine similarity with HNSW index
    start_time := clock_timestamp();
    
    SELECT COUNT(*) INTO result_count
    FROM (
        SELECT e.id
        FROM analytics.embeddings e
        ORDER BY e.embedding <=> test_embedding
        LIMIT limit_results
    ) sub;
    
    end_time := clock_timestamp();
    
    RETURN QUERY SELECT 
        'cosine_hnsw'::text,
        EXTRACT(epoch FROM (end_time - start_time)) * 1000,
        result_count;

    -- Test 2: L2 distance
    start_time := clock_timestamp();
    
    SELECT COUNT(*) INTO result_count
    FROM (
        SELECT e.id
        FROM analytics.embeddings e
        ORDER BY e.embedding <-> test_embedding
        LIMIT limit_results
    ) sub;
    
    end_time := clock_timestamp();
    
    RETURN QUERY SELECT 
        'l2_distance'::text,
        EXTRACT(epoch FROM (end_time - start_time)) * 1000,
        result_count;

    -- Test 3: Inner product
    start_time := clock_timestamp();
    
    SELECT COUNT(*) INTO result_count
    FROM (
        SELECT e.id
        FROM analytics.embeddings e
        ORDER BY e.embedding <#> test_embedding DESC
        LIMIT limit_results
    ) sub;
    
    end_time := clock_timestamp();
    
    RETURN QUERY SELECT 
        'inner_product'::text,
        EXTRACT(epoch FROM (end_time - start_time)) * 1000,
        result_count;
END;
$$ LANGUAGE plpgsql;

