-- Find zones with similar growth patterns using sensor data embeddings
-- This helps identify optimal growing conditions and predict outcomes

WITH target_zone_embedding AS (
    SELECT embedding
    FROM analytics.embeddings 
    WHERE entity_type = 'growth_pattern' 
      AND entity_id = '770e8400-e29b-41d4-a716-446655440001' -- Target zone
      AND model_name = 'growth_pattern_model_v1'
    LIMIT 1
)
SELECT 
    e.entity_id as zone_id,
    z.name as zone_name,
    z.plant_type,
    g.name as garden_name,
    u.name as owner_name,
    -- Similarity score
    1 - (e.embedding <=> tze.embedding) as pattern_similarity,
    -- Additional context
    z.metadata->'varieties' as plant_varieties,
    z.metadata->'planting_date' as planting_date
FROM analytics.embeddings e
JOIN gardens.zones z ON z.id = e.entity_id::uuid
JOIN gardens.gardens g ON g.id = z.garden_id
JOIN auth.users u ON u.id = g.user_id
CROSS JOIN target_zone_embedding tze
WHERE e.entity_type = 'growth_pattern'
  AND e.model_name = 'growth_pattern_model_v1'
  AND e.entity_id != '770e8400-e29b-41d4-a716-446655440001' -- Exclude the target zone
ORDER BY e.embedding <=> tze.embedding
LIMIT 10;

