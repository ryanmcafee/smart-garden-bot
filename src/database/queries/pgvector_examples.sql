-- Find unusual sensor reading patterns using vector embeddings
-- This helps identify potential issues with plants or equipment

CREATE OR REPLACE FUNCTION detect_sensor_anomalies(
    zone_id_param uuid,
    lookback_days int DEFAULT 7,
    anomaly_threshold float DEFAULT 0.6
)
RETURNS TABLE (
    timestamp_anomaly timestamp with time zone,
    anomaly_score float,
    sensor_values jsonb,
    similar_normal_patterns text[]
) AS $$
BEGIN
    RETURN QUERY
    WITH recent_readings AS (
        -- Get recent sensor readings for the zone
        SELECT 
            timestamp,
            json_build_object(
                'temperature', temperature,
                'humidity', humidity,
                'soil_moisture', soil_moisture,
                'soil_temperature', soil_temperature,
                'light_intensity', light_intensity
            ) as reading_values
        FROM sensors.readings sr
        WHERE sr.zone_id = zone_id_param
          AND sr.timestamp >= CURRENT_TIMESTAMP - (lookback_days || ' days')::interval
        ORDER BY timestamp DESC
    ),
    reading_embeddings AS (
        -- In practice, these embeddings would be generated by your ML pipeline
        -- This is a simplified example showing the structure
        SELECT 
            rr.timestamp,
            rr.reading_values,
            -- Placeholder: embeddings would be generated from the sensor values
            -- using a trained model that understands normal vs anomalous patterns
            e.embedding
        FROM recent_readings rr
        JOIN analytics.embeddings e ON e.entity_type = 'sensor_reading'
          AND e.created_at::date = rr.timestamp::date
        WHERE e.model_name = 'sensor_anomaly_model_v1'
    ),
    normal_pattern_baseline AS (
        -- Get embeddings representing normal sensor patterns for this zone
        SELECT AVG(e.embedding) as normal_embedding
        FROM analytics.embeddings e
        WHERE e.entity_type = 'normal_sensor_pattern'
          AND e.entity_id = zone_id_param::text
          AND e.model_name = 'sensor_anomaly_model_v1'
    )
    SELECT 
        re.timestamp as timestamp_anomaly,
        (1 - (re.embedding <=> npb.normal_embedding))::float as anomaly_score,
        re.reading_values as sensor_values,
        ARRAY['High soil moisture with low humidity', 'Temperature spike detected']::text[] as similar_normal_patterns
    FROM reading_embeddings re
    CROSS JOIN normal_pattern_baseline npb
    WHERE (1 - (re.embedding <=> npb.normal_embedding)) < anomaly_threshold
    ORDER BY (re.embedding <=> npb.normal_embedding) DESC
    LIMIT 20;
END;
$$ LANGUAGE plpgsql;

