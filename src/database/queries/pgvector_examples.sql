-- Function to calculate embedding statistics
CREATE OR REPLACE FUNCTION embedding_statistics(
    entity_type_param text DEFAULT NULL,
    model_name_param text DEFAULT NULL
)
RETURNS TABLE (
    entity_type text,
    model_name text,
    total_embeddings bigint,
    avg_vector_norm float,
    dimension_count int
) AS $$
BEGIN
    RETURN QUERY
    SELECT 
        e.entity_type,
        e.model_name,
        COUNT(*) as total_embeddings,
        AVG(sqrt((e.embedding <#> e.embedding))) as avg_vector_norm,
        vector_dims(e.embedding) as dimension_count
    FROM analytics.embeddings e
    WHERE (entity_type_param IS NULL OR e.entity_type = entity_type_param)
      AND (model_name_param IS NULL OR e.model_name = model_name_param)
    GROUP BY e.entity_type, e.model_name, vector_dims(e.embedding)
    ORDER BY total_embeddings DESC;
END;
$$ LANGUAGE plpgsql;

