-- Find similar plant diseases based on image embeddings
-- This query finds the top 5 most similar disease cases to a given plant image

WITH query_embedding AS (
    -- In practice, this would be the embedding of the query image
    -- generated by your ML model (e.g., a 512-dimensional vector)
    SELECT '[0.1, 0.2, 0.3, ..., 0.512]'::vector(512) as embedding
)
SELECT 
    pdd.id,
    pdd.zone_id,
    z.name as zone_name,
    pdd.detected_diseases,
    pdd.confidence_scores,
    pdd.processed_at,
    -- Calculate cosine similarity (1 - cosine distance)
    1 - (e.embedding <=> qe.embedding) as similarity_score
FROM analytics.plant_disease_detections pdd
JOIN analytics.embeddings e ON e.entity_id = pdd.id AND e.entity_type = 'plant_image'
JOIN gardens.zones z ON z.id = pdd.zone_id
CROSS JOIN query_embedding qe
WHERE e.model_name = 'plant_disease_model_v2'
ORDER BY e.embedding <=> qe.embedding  -- Order by cosine distance (ascending)
LIMIT 5;

