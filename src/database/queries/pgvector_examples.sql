-- Create optimized indexes for vector similarity searches
-- These indexes significantly improve query performance

-- HNSW index for fast approximate nearest neighbor search
CREATE INDEX IF NOT EXISTS idx_embeddings_hnsw_cosine 
ON analytics.embeddings 
USING hnsw (embedding vector_cosine_ops)
WITH (m = 16, ef_construction = 64);

-- IVFFlat index for better recall on smaller datasets
CREATE INDEX IF NOT EXISTS idx_embeddings_ivfflat_cosine 
ON analytics.embeddings 
USING ivfflat (embedding vector_cosine_ops)
WITH (lists = 100);

-- Partial indexes for specific entity types (better performance)
CREATE INDEX IF NOT EXISTS idx_embeddings_plant_disease_hnsw
ON analytics.embeddings 
USING hnsw (embedding vector_cosine_ops)
WHERE entity_type = 'plant_image';

