-- 6. OPTIMAL WATERING TIME PREDICTION
-- =============================================

-- Use vector similarity to predict optimal watering times based on 
-- environmental conditions, plant needs, and historical success

WITH current_conditions AS (
    -- Current environmental conditions as embedding
    SELECT 
        e.embedding as conditions_vector,
        sr.zone_id,
        sr.timestamp as current_time
    FROM sensors.readings sr
    JOIN analytics.embeddings e ON e.entity_type = 'environmental_conditions'
      AND e.created_at::date = sr.timestamp::date
    WHERE sr.zone_id = '770e8400-e29b-41d4-a716-446655440001'
      AND e.model_name = 'environmental_model_v1'
    ORDER BY sr.timestamp DESC
    LIMIT 1
),
historical_success_patterns AS (
    -- Find historically successful watering times under similar conditions
    SELECT 
        we.started_at,
        extract(hour from we.started_at) as watering_hour,
        we.actual_duration_minutes,
        we.water_volume_liters,
        we.soil_moisture_before,
        we.soil_moisture_after,
        e.embedding as historical_conditions,
        1 - (e.embedding <=> cc.conditions_vector) as condition_similarity,
        -- Success metrics
        CASE 
            WHEN we.status = 'completed' AND (we.soil_moisture_after - we.soil_moisture_before) > 20 
            THEN 1.0 
            ELSE 0.0 
        END as success_score
    FROM sensors.watering_events we
    JOIN analytics.embeddings e ON e.entity_type = 'environmental_conditions'
      AND e.created_at::date = we.started_at::date
    CROSS JOIN current_conditions cc
    WHERE we.zone_id = cc.zone_id
      AND e.model_name = 'environmental_model_v1'
      AND we.started_at >= CURRENT_TIMESTAMP - INTERVAL '90 days' -- Last 3 months
      AND (1 - (e.embedding <=> cc.conditions_vector)) > 0.8 -- 80% similar conditions
)
SELECT 
    watering_hour,
    COUNT(*) as frequency,
    AVG(success_score) as avg_success_rate,
    AVG(condition_similarity) as avg_condition_match,
    AVG(actual_duration_minutes) as recommended_duration,
    AVG(soil_moisture_after - soil_moisture_before) as avg_moisture_increase,
    -- Overall recommendation score
    (AVG(success_score) * 0.5 + AVG(condition_similarity) * 0.3 + COUNT(*)::float/10 * 0.2) as recommendation_score
FROM historical_success_patterns
GROUP BY watering_hour
HAVING COUNT(*) >= 3 -- At least 3 historical src
ORDER BY recommendation_score DESC
LIMIT 5;

