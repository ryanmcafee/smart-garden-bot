-- Function to clean up old embeddings
CREATE OR REPLACE FUNCTION cleanup_old_embeddings(
    days_to_keep int DEFAULT 365,
    dry_run boolean DEFAULT true
)
RETURNS TABLE (
    action text,
    entity_type text,
    model_name text,
    affected_rows bigint
) AS $$
DECLARE
    cleanup_date timestamp with time zone;
    rec record;
    delete_count bigint;
BEGIN
    cleanup_date := CURRENT_TIMESTAMP - (days_to_keep || ' days')::interval;
    
    FOR rec IN 
        SELECT e.entity_type, e.model_name, COUNT(*) as old_count
        FROM analytics.embeddings e
        WHERE e.created_at < cleanup_date
        GROUP BY e.entity_type, e.model_name
    LOOP
        IF dry_run THEN
            RETURN QUERY SELECT 
                'DRY_RUN_DELETE'::text,
                rec.entity_type,
                rec.model_name,
                rec.old_count;
        ELSE
            DELETE FROM analytics.embeddings
            WHERE entity_type = rec.entity_type
              AND model_name = rec.model_name
              AND created_at < cleanup_date;
            
            GET DIAGNOSTICS delete_count = ROW_COUNT;
            
            RETURN QUERY SELECT 
                'DELETED'::text,
                rec.entity_type,
                rec.model_name,
                delete_count;
        END IF;
    END LOOP;
END;
$$ LANGUAGE plpgsql;

