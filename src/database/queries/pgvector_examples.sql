-- 3. WEATHER PATTERN MATCHING
-- =============================================

-- Find historical weather patterns similar to current conditions
-- Useful for predicting optimal watering schedules and plant care

CREATE OR REPLACE FUNCTION find_similar_weather_patterns(
    query_vector vector(512),
    similarity_threshold float DEFAULT 0.7,
    limit_results int DEFAULT 20
)
RETURNS TABLE (
    pattern_date date,
    similarity_score float,
    weather_data jsonb,
    watering_events_count bigint,
    avg_soil_moisture float
) AS $$
BEGIN
    RETURN QUERY
    WITH similar_patterns AS (
        SELECT 
            e.entity_id,
            1 - (e.embedding <=> query_vector) as similarity,
            e.created_at::date as pattern_date
        FROM analytics.embeddings e
        WHERE e.entity_type = 'weather_pattern'
          AND e.model_name = 'weather_pattern_model_v1'
          AND (1 - (e.embedding <=> query_vector)) >= similarity_threshold
        ORDER BY e.embedding <=> query_vector
        LIMIT limit_results
    ),
    pattern_context AS (
        SELECT 
            sp.entity_id,
            sp.similarity,
            sp.pattern_date,
            wd.data as weather_data,
            COUNT(we.id) as watering_count,
            AVG(sr.soil_moisture) as avg_moisture
        FROM similar_patterns sp
        LEFT JOIN sensors.weather_data wd ON wd.id = sp.entity_id::uuid
        LEFT JOIN sensors.watering_events we ON we.started_at::date = sp.pattern_date
        LEFT JOIN sensors.readings sr ON sr.timestamp::date = sp.pattern_date
        GROUP BY sp.entity_id, sp.similarity, sp.pattern_date, wd.data
    )
    SELECT 
        pc.pattern_date,
        pc.similarity::float as similarity_score,
        pc.weather_data,
        pc.watering_count,
        pc.avg_moisture::float
    FROM pattern_context pc
    ORDER BY pc.similarity DESC;
END;
$$ LANGUAGE plpgsql;

